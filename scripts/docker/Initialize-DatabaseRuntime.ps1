$ErrorActionPreference = "Stop"

$root = [IO.Path]::GetFullPath(
    (Join-Path (Join-Path $PSScriptRoot "..") "..")
)

Push-Location $root

try {
    $utf8 = New-Object System.Text.UTF8Encoding($false)
    $envPath = Join-Path $root ".env"
    $examplePath = Join-Path $root ".env.example"

    if (-not (Test-Path -LiteralPath $envPath)) {
        throw "Configure the local .env file first."
    }

    if (
        (Test-Path Env:FIELDOPS_SQL_SA_PASSWORD) -or
        (Test-Path Env:FIELDOPS_SQL_APP_PASSWORD)
    ) {
        throw "Conflicting SQL environment variables detected."
    }

    $sqlContainerId = docker compose ps -q sqlserver

    if (
        $LASTEXITCODE -ne 0 -or
        [string]::IsNullOrWhiteSpace($sqlContainerId)
    ) {
        throw "SQL Server container is not running."
    }

    $sqlHealth = docker inspect $sqlContainerId `
        --format '{{.State.Health.Status}}'

    if ($LASTEXITCODE -ne 0 -or $sqlHealth -ne "healthy") {
        throw "SQL Server container is not healthy."
    }

    $mountJson = docker inspect $sqlContainerId `
        --format '{{json .Mounts}}'

    if ($LASTEXITCODE -ne 0) {
        throw "Unable to inspect SQL Server storage."
    }

    $mountItems = $mountJson | ConvertFrom-Json

    $dataMount = @(
        $mountItems | Where-Object {
            $_.Name -eq "fieldops360_sqlserver-data" -and
            $_.Destination -eq "/var/opt/mssql" -and
            $_.Type -eq "volume" -and
            $_.RW -eq $true
        }
    )

    if ($dataMount.Count -ne 1) {
        throw "Unexpected SQL Server data volume."
    }

    Write-Host "[OK] SQL Server volume verified."
    Write-Host "Volume: $($dataMount[0].Name)"
    Write-Host "Mount:  $($dataMount[0].Destination)"

    $envContent = [IO.File]::ReadAllText($envPath)

    $passwordEntries = [regex]::Matches(
        $envContent,
        '(?m)^FIELDOPS_SQL_APP_PASSWORD=([^\r\n]+)'
    )

    if ($passwordEntries.Count -gt 1) {
        throw "Duplicate application password entries."
    }

    if ($passwordEntries.Count -eq 0) {

        $randomBytes = New-Object byte[] 24
        $generator = [Security.Cryptography.RandomNumberGenerator]::Create()

        try {
            $generator.GetBytes($randomBytes)
        }
        finally {
            $generator.Dispose()
        }

        $appPassword = "Aa1!" + (
            [BitConverter]::ToString($randomBytes).Replace("-", "")
        )

        $envContent = $envContent.TrimEnd() +
            "`nFIELDOPS_SQL_APP_PASSWORD=$appPassword`n"

        [IO.File]::WriteAllText(
            $envPath,
            $envContent,
            $utf8
        )

        Write-Host "[OK] Application password generated securely."
    }
    else {
        $appPassword = $passwordEntries[0].Groups[1].Value

        Write-Host "[OK] Existing application password preserved."
    }

    # The restricted character set allows safe SQL substitution.
    if ($appPassword -notmatch '^Aa1![A-F0-9]{48}$') {
        throw "Unexpected application password format."
    }

    $exampleContent = [IO.File]::ReadAllText($examplePath)

    if ($exampleContent -notmatch '(?m)^FIELDOPS_SQL_APP_PASSWORD=') {

        $exampleContent = $exampleContent.TrimEnd() +
            "`n`n# Runtime database account password (generated by the provisioning script).`n" +
            "FIELDOPS_SQL_APP_PASSWORD=REPLACE_WITH_GENERATED_PASSWORD`n"

        [IO.File]::WriteAllText(
            $examplePath,
            $exampleContent,
            $utf8
        )
    }

    $sqlTemplate = [IO.File]::ReadAllText(
        (Join-Path $PSScriptRoot "provision-runtime.sql")
    )

    $sqlToExecute = $sqlTemplate.Replace(
        "__FIELDOPS_APP_PASSWORD__",
        $appPassword
    )

    Write-Host "`n=== SQL RUNTIME PROVISIONING ===" -ForegroundColor Cyan

    $previousPreference = $ErrorActionPreference

    try {
        $ErrorActionPreference = "Continue"

        $sqlOutput = @(
            $sqlToExecute |
                docker compose exec -T sqlserver sh -c `
                'export SQLCMDPASSWORD=$MSSQL_SA_PASSWORD; exec /opt/mssql-tools18/bin/sqlcmd -S localhost -U sa -C -b -W' 2>&1
        )

        $sqlExitCode = $LASTEXITCODE
    }
    finally {
        $ErrorActionPreference = $previousPreference
    }

    $sqlOutput | ForEach-Object {
        $_.ToString().Replace($appPassword, "[REDACTED]")
    } | Write-Host

    if ($sqlExitCode -ne 0) {
        throw "SQL runtime provisioning failed."
    }

    # Verify authentication with the actual application credentials.
    Write-Host "`n=== APPLICATION LOGIN VERIFICATION ===" -ForegroundColor Cyan

    $loginInput = @(
        $appPassword
        "SET NOCOUNT ON;"
        "SELECT SUSER_SNAME(), DB_NAME();"
        "GO"
    )

    try {
        $ErrorActionPreference = "Continue"

        $loginOutput = @(
            $loginInput |
                docker compose exec -T sqlserver sh -c `
                'IFS= read -r pw; SQLCMDPASSWORD=$(printf %s $pw | tr -d \\015); export SQLCMDPASSWORD; exec /opt/mssql-tools18/bin/sqlcmd -S localhost -U fieldops_app -C -b -d FieldOpsDockerDb -h -1 -W' 2>&1
        )

        $loginExitCode = $LASTEXITCODE
    }
    finally {
        $ErrorActionPreference = $previousPreference
    }

    $loginOutput | ForEach-Object {
        $_.ToString().Replace($appPassword, "[REDACTED]")
    } | Write-Host

    if (
        $loginExitCode -ne 0 -or
        ($loginOutput -join "`n") -notmatch 'fieldops_app\s+FieldOpsDockerDb'
    ) {
        throw "Application database authentication failed."
    }

    Write-Host "[OK] Application SQL authentication verified." -ForegroundColor Green
    Write-Host "[OK] Restricted runtime permissions verified." -ForegroundColor Green
}
finally {
    Remove-Variable appPassword, sqlToExecute, loginInput, envContent -ErrorAction SilentlyContinue
    Pop-Location
}
